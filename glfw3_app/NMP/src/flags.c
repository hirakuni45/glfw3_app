void ReciveValues(int no)
{
	char	*ptr;

	if(no==0) return;

	ptr = (char *)(get_SATURN_DRAM_TOP() + 0xfffe0);

	randSeed = *(int *)ptr; ptr += 4;
	randBase1 = *(int *)ptr; ptr += 4;
	randBase2 = *(int *)ptr; ptr += 4;
	startMaskEnable = *ptr++;
	demoPlayIndex = *ptr++;
	mainMenuPos = *ptr++;
	gameMenuPos = *ptr++;
	playerNo = *ptr++;
	realmsEnable = *ptr++;
	titleMovieIndex = *ptr++;
}

void TransmitValues(void)
{
	char	*ptr;

	ptr = (char *)(get_SATURN_DRAM_TOP() + 0xfffe0);

	*(int *)ptr = randSeed; ptr += 4;
	*(int *)ptr = randBase1; ptr += 4;
	*(int *)ptr = randBase2; ptr += 4;
	*ptr++ = startMaskEnable;
	*ptr++ = demoPlayIndex;
	*ptr++ = mainMenuPos;
	*ptr++ = gameMenuPos;
	*ptr++ = playerNo;
	*ptr++ = realmsEnable;
	*ptr++ = titleMovieIndex;
}

