void MobjInfo(int x, int y, int no, int sx, int sy)
{
	int	h, v, ox, oy, f;
	MOBJ	*mobj;

	if(sx == 0 || sy == 0) return;

	ox = infoOfsX;
	oy = infoOfsY;
	if(ox | oy) f = 1; else f = 0;

	mobj = infoAnime.mobj + no;
	h = mobj->h;
	v = mobj->v;
	h *= sx; h >>= 8;
	v *= sy; v >>= 8;
	if(f) {
	ox *= sx; ox >>= 8;
	oy *= sy; oy >>= 8;
	mobj->x = x + ox;
	mobj->y = y + oy;
	}
	else {
	mobj->x = x - (h / 2);
	mobj->y = y - (v / 2);
	}
	mobj->color = 0;
	SetupResizeObject(mobj, h-1, v-1);
}

