void ExtractBitFrame(int *in)
{
	int	i, f;
	unsigned int	a, b;
	unsigned char	idx[4], *ptr, c, d;
	unsigned short	*dst;
	unsigned int	*dst2;
	MOBJ	*mobj;

	ptr = (unsigned char *)in;
	mobj = info2Anime.mobj;
	dst = (unsigned short *)get_VDP1_VRAM_TOP();
	dst += ((unsigned short)mobj->chaptr) << 2;

	dst2 = (unsigned int *)dst;

	ptr += 5;
	f = *ptr++;
	ptr += 2;
	idx[0] = *ptr++;
	idx[1] = *ptr++;
	idx[2] = *ptr++;
	idx[3] = *ptr++;

	c = *ptr++;	/* OP Code 1 */
	ptr += 3;

	if(f > 2) {
	d = 0;
	for(i=0; i<(256 * 96 / 4); ++i) {
	if(d==0) a = *ptr++;
	if(a==c) { a = *ptr++; d = *ptr++; }
		if(d) d--;
		b  = idx[(a >> 6) & 3];
		b <<= 4;
		b |= idx[(a >> 4) & 3];
		b <<= 4;
		b |= idx[(a >> 2) & 3];
		b <<= 4;
		b |= idx[a & 3];
		*dst++ = b;
		}
	}
	else	{
	d = 0;
	for(i=0; i<(256 * 96 / 8); ++i) {
	if(d==0) a = *ptr++;
	if(a==c) { a = *ptr++; d = *ptr++; }
		if(d) d--;
		b  = idx[(a >> 7) & 1];
		b <<= 4;
		b |= idx[(a >> 6) & 1];
		b <<= 4;
		b |= idx[(a >> 5) & 1];
		b <<= 4;
		b |= idx[(a >> 4) & 1];
		b <<= 4;
		b |= idx[(a >> 3) & 1];
		b <<= 4;
		b |= idx[(a >> 2) & 1];
		b <<= 4;
		b |= idx[(a >> 1) & 1];
		b <<= 4;
		b |= idx[a & 1];
		*dst2++ = b;
		}
	}
}

