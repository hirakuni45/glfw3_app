void MobjInfoTexts(int x, int y, int s, const char *t)
{
	int	c, j, l, m, tag[8], o;
	char	*top, na, nb, nc, *p;

	if(t==NULL) return;

	p = infoTextBuffer;

	while((c = *t++) != 0) {
	if(c=='@') {
		top = infoText[infoTextNo];
		while((*p++ = *top++) != 0) ;
		}
	*p++ = c;
	}
	*p = 0;

	t = top = infoTextBuffer;
	j = 0;
	l = 0;
	o = s * 61;
	while((c = *t++) != 0) {
	if(c==' ') {
		l += infoFontSizeTables[o + 41] * 2;
		l += infoFontSizeTables[o + 40] * 2;
		}
	else if(c=='/') { tag[j] = l; j++; l = 0; }
	else if(c=='#') {
		nc = infoNumber % 10;
		nb = infoNumber / 10;
		na = nb / 10; 
		nb %= 10;
		if(na) l += infoFontSizeTables[o + na + 30] * 2;
		if(na | nb) l += infoFontSizeTables[o + nb + 30] * 2;
		l += infoFontSizeTables[o + nc + 30] * 2;
		}
	else if(c=='%') {
		nb = infoNumber % 10;
		l += infoFontSizeTables[o + nb + 30] * 2;
		}
	else if(c=='@') {
		p = infoText[infoTextNo];
		while((c = *p++) != 0) {
			c = InfoTextCode(c);
			l += infoFontSizeTables[o + c] * 2;
			l += infoFontSizeTables[o + 40] * 2;
			}
		}
	else	{
		c = InfoTextCode(c);
		l += infoFontSizeTables[o + c] * 2;
		l += infoFontSizeTables[o + 40] * 2;
		}
	}
	tag[j] = l;

	j++;
	y -= j * infoFontSizeTables[o + 42];
	j = 0;
	l = x - tag[j] / 2;
	while((c = *top++) != 0) {
	if(c==' ') {
		l += infoFontSizeTables[o + 41] * 2;
		l += infoFontSizeTables[o + 40] * 2;
		}
	else if(c=='/') {
		j++;
		l = x - tag[j] / 2;
		y += infoFontSizeTables[o + 42] * 2;
		}
	else if(c=='#') {
		if(na) {
			l += MobjInfoText(l, y, s, na + 30);
			l += infoFontSizeTables[o + 40] * 2;
			}
		if(na | nb) {
			l += MobjInfoText(l, y, s, nb + 30);
			l += infoFontSizeTables[o + 40] * 2;
			}
		l += MobjInfoText(l, y, s, nc + 30);
		l += infoFontSizeTables[o + 40] * 2;		
		}
	else if(c=='%') {
		l += MobjInfoText(l, y, s, nb + 30);
		l += infoFontSizeTables[o + 40] * 2;
		}
	else if(c=='@') {
		p = infoText[infoTextNo];
		while((c = *p++) != 0) {
			c = InfoTextCode(c);
			l += MobjInfoText(l, y, s, c);
			l += infoFontSizeTables[o + 40] * 2;
			}
		}
	else	{
		c = InfoTextCode(c);
		l += MobjInfoText(l, y, s, c);
		l += infoFontSizeTables[o + 40] * 2;
		}
	}
}

int InfoTextCode(int c)
{
	if(c >= 'A' && c <= 'Z') c -= 'A';
	else if(c >= 'a' && c <= 'z') c -= 'a';
	else if(c >= '0' && c <= '9') { c -= 0x30; c += 30; }
	else if(c == ',') c = 26;
	else if(c == '\'') c = 27;
	else if(c == '.') c = 28;
	else if(c == ':') c = 29;
	else c = 0;
	return c;
}

